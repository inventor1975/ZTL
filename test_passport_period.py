"""Стенд: паспорт несёт период для КАЖДОЙ циклической компоненты.

Зачем. Период печатался только там, где классических моделей ноль — то есть
только у PARADOX. Из-за этого правдивец `τ ≡ τ` и чётный цикл `A ≡ ¬B, B ≡ ¬A`
выдавали ОДИН И ТОТ ЖЕ паспорт дословно — «2 classical models; refusal until
stipulation», — хотя их жадные периоды 1 и 2, и `zparadox` мерил эту разницу с
самого начала. Различие было промерено и невидимо.

Число моделей отвечает на вопрос «сколькими способами это можно уладить».
Период отвечает на другой: «что машина делает, пока не уладили». Ни один из
двух не выводится из другого — потому и нужны оба.

Каждая проверка с КОНТРОЛЕМ: мало показать, что паспорта РАЗОШЛИСЬ, — надо
показать, что там, где различия нет, они по-прежнему совпадают, иначе стенд
доволен прибором, который просто печатает разное всем подряд.
"""
import sys

import zpassport as Z

ok = fail = 0


def check(имя, cond, why=""):
    global ok, fail
    if cond:
        ok += 1
        print(f"  OK   {имя}")
    else:
        fail += 1
        print(f"  FAIL {имя} — {why}")


def паспорт(system):
    _, reports, _ = Z.passports(system)
    return reports[0][1], reports[0][2]


ПРАВДИВЕЦ = {"τ": "τ"}
ЧЁТНЫЙ = {"A": ("not", "B"), "B": ("not", "A")}
ЛЖЕЦ = {"λ": ("not", "λ")}

k1, d1 = паспорт(ПРАВДИВЕЦ)
k2, d2 = паспорт(ЧЁТНЫЙ)
kл, dл = паспорт(ЛЖЕЦ)

check("правдивец и чётный цикл — оба UNDERDETERMINED",
      k1 == k2 == "UNDERDETERMINED", f"{k1} / {k2}")
check("и у обоих по 2 классические модели",
      "2 classical models" in d1 and "2 classical models" in d2)
check("ПАСПОРТА ТЕПЕРЬ РАЗЛИЧАЮТСЯ", d1 != d2,
      "различие промерено, а читателю по-прежнему невидимо")
check("правдивец несёт период 1", "oscillation period 1" in d1, d1)
check("чётный цикл несёт период 2", "oscillation period 2" in d2, d2)

check("КОНТРОЛЬ: лжец по-прежнему PARADOX с периодом 2",
      kл == "PARADOX" and "oscillation period 2" in dл, dл)
check("КОНТРОЛЬ: у лжеца отказ ПОСТОЯННЫЙ, а у циклов — до оговорки",
      "PERMANENT" in dл and "until stipulation" in d1,
      "правка размыла разницу между постоянным отказом и снимаемым")

# КОНТРОЛЬ КОНТРОЛЯ: период не выводится из числа моделей. Если бы выводился,
# различать паспорта было бы нечем нового, и вся правка была бы украшением.
check("КОНТРОЛЬ: период НЕ выводим из числа моделей",
      ("2 classical models" in d1 and "2 classical models" in d2
       and "period 1" in d1 and "period 2" in d2),
      "одинаковое число моделей при разных периодах — этого и не должно быть видно")

# КОНТРОЛЬ: заземлённая система не получает периода вовсе — печатать его там
# значило бы сообщать о колебании, которого нет.
_, rep_g, _ = Z.passports({"p": "T", "q": ("not", "p")})
check("КОНТРОЛЬ: заземлённое не получает периода",
      all("oscillation period" not in r[2] for r in rep_g),
      f"{[r[2] for r in rep_g]}")

print(f"\nPASSPORT-PERIOD {'GREEN' if not fail else 'RED'}: {ok} OK, {fail} FAIL")
sys.exit(1 if fail else 0)

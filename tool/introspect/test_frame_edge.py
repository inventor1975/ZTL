#!/usr/bin/env python3
"""Ярус 3: КРАЙ РАМКИ у соблазна — требование и его проверка.

Слово куратора 2026-08-26, на разборе Макиавелли: «казни государя задевают ЛИШЬ
отдельного человека, тогда как беспорядок ранит целый народ». Верно, если считать
только тела, до которых дотянулись; ложно, едва рамку расширить. Его вывод:
НОЖ — НЕ ВЫВОД, НОЖ — ТО, ЧТО ВЫНЕСЕНО ЗА КРАЙ.

Рубрика умела спросить, В ЧЁМ оборачивание, и не умела спросить, ЧТО ОТРЕЗАНО.
Это разные вопросы: первый про механизм, второй про улику. Промерено 2026-08-29:
слов «отрезано», «за край», «сужение» в рубрике было НОЛЬ.

Стенд держит обе половины: что рубрика ТРЕБУЕТ край, и что сборка его СЧИТАЕТ.
Требование без счёта — пожелание: судья-форк забудет, и никто не заметит.
"""
from __future__ import annotations
import pathlib
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import zchoose                                                # noqa: E402


def main() -> int:
    ok = fail = 0

    def check(name, cond, detail=""):
        nonlocal ok, fail
        print(f"  {'OK ' if cond else 'FAIL'} {name}" + (f" — {detail}" if detail and not cond else ""))
        ok += bool(cond); fail += (not cond)

    # ── рубрика ────────────────────────────────────────────────────────────
    check("рубрика ТРЕБУЕТ назвать, что отрезано", "отрезано:" in zchoose.RUBRIC)
    check("и говорит про край рамки", "за край" in zchoose.RUBRIC)
    check("и различает: отрезать нечего → НЕ S",
          "НЕ S" in zchoose.RUBRIC)

    def ledger(*строки):
        d = pathlib.Path(tempfile.mkdtemp())
        (d / "verdict-01.md").write_text("\n".join(строки), encoding="utf-8")
        out = d / "ledger.md"
        zchoose.assemble(d, out, "проба")
        return out.read_text(encoding="utf-8")

    # ── УДАР: соблазн БЕЗ края рамки должен быть назван вслух ──────────────
    txt = ledger("- «казни задевают лишь одного» — [S] — рамка сужена до тел")
    check("S без «отрезано:» — ПОМЕЧЕН вслух",
          "КРАЙ РАМКИ НЕ НАЗВАН" in txt and "1 ход" in txt)

    # ── КОНТРОЛЬ: с краем рамки — НЕ помечен. Без него проверка бессмысленна:
    #    пометка, стоящая всегда, не отличает хорошее от плохого.
    txt2 = ledger("- «казни задевают лишь одного» — [S] — рамка сужена; "
                  "отрезано: те, кого беспорядок убьёт потом")
    check("КОНТРОЛЬ: S С «отрезано:» — НЕ помечен",
          "КРАЙ РАМКИ НЕ НАЗВАН" not in txt2 and "Край рамки назван у всех" in txt2)

    # ── T? держится тем же правилом ────────────────────────────────────────
    txt3 = ledger("- «инвариант держится сейчас» — [T?] — обернётся при ином входе")
    check("T? без края — тоже помечен", "КРАЙ РАМКИ НЕ НАЗВАН" in txt3)

    # ── и там, где судить нечего, пометки быть не должно ───────────────────
    txt4 = ledger("- «дважды два четыре» — [T] — стоит само")
    check("ходов S/T? нет — сказано, что называть нечего",
          "называть не у чего" in txt4)

    print(f"\n  итог: {ok} OK, {fail} FAIL")
    if fail == 0:
        print("FRAME EDGE GREEN — соблазн обязан предъявить ОБРЕЗОК, "
              "а не только вывод; забыл — сказано вслух, назвал — молчим.")
    return 1 if fail else 0


if __name__ == "__main__":
    raise SystemExit(main())

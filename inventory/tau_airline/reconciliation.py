    print(f"\n  задач с отменой и БЕЗ компенсации/бронирования: {cancel_only}")
    print(f"  задач с отменой И компенсацией/бронированием   : {both}"
          f"  <- экономия ИСПАРЯЕТСЯ")

    print("\n" + "=" * 68)
    print("ИТОГОВОЕ РАЗЛОЖЕНИЕ ПО ЗАМОРОЖЕННОМУ КОРПУСУ")
    print("=" * 68)

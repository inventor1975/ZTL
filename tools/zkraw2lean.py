"""zkraw2lean — a SYSTEM of laws F(x) = 0 (exp / ln / log10 / division / powers) as a Lean theorem on VR's continuum:
a solution in a cube, and only one there (lean/ZKrawSys.lean, `sys_root`).

    python3 tools/zkraw2lean.py circle_exp      (writes lean/ZSysCircleExp.lean)
    python3 tools/zkraw2lean.py chem3

Untrusted search, checked result. Python only PROPOSES: Newton in floats for the centre y, the preconditioner
Y ≈ J(y)⁻¹, the matrix Z ≈ J(y), the cube radius r. Lean's kernel CHECKS (`decide +kernel`):
  chkK — for G(x) = x − Y·F(x): every denominator / ln argument reads ≥ 2⁻⁶⁴ on the cube; each row of the staircase
         slope readings sums to ≤ ½ (contraction); G(centre) ± r/2 lies in the cube shrunk by 2⁻ᴿ (into);
  chkZ — every row of |I − Z·Y| (exact dyadic arithmetic) sums to ≤ ½ (Y invertible).
The laws are read by znumjudge._parse_arith and translated node for node (tools/zlaw2lean.py).
"""
import math, os, sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LEAN = os.path.join(ROOT, "lean")
sys.path.insert(0, ROOT); sys.path.insert(0, HERE)
import zlaw2lean as Z  # noqa: E402

SYSTEMS = {
    "circle_exp": dict(vars=["x", "y"], laws=["x*x + y*y - 1", "x - exp(y)"], guess=[0.5, -0.5],
                       title="the circle meets the exponential: x² + y² = 1, x = eʸ"),
    "chem3": dict(vars=["x", "y", "z"], laws=["x + y + z - 3", "x*exp(y) - 2", "ln(z) + x*y - 1/2"],
                  guess=[1.0, 0.5, 1.5], title="a 3×3 system with exp and ln: x + y + z = 3, x·eʸ = 2, ln z + x·y = ½"),
}


def fl(node, env):
    if isinstance(node, (F, int)):
        return float(node)
    if isinstance(node, str):
        return env[node]
    op = node[0]
    a = fl(node[1], env)
    if op == "log10":
        return math.log10(a)
    if op == "exp":
        return math.exp(a)
    if op == "ln":
        return math.log(a)
    b = fl(node[2], env)
    if op == "add":
        return a + b
    if op == "sub":
        return a - b
    if op == "mul":
        return a * b
    if op == "div":
        return a / b
    if op == "pow":
        return a ** b
    raise ValueError(op)


def solve(A, b):
    n = len(A); M = [row[:] + [b[i]] for i, row in enumerate(A)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(M[r][c])); M[c], M[p] = M[p], M[c]
        for r in range(n):
            if r != c:
                f = M[r][c] / M[c][c]
                M[r] = [x - f * y for x, y in zip(M[r], M[c])]
    return [M[i][n] / M[i][i] for i in range(n)]


def inv(A):
    n = len(A)
    cols = [solve(A, [1.0 if i == j else 0.0 for i in range(n)]) for j in range(n)]
    return [[cols[j][i] for j in range(n)] for i in range(n)]


def lst(xs):
    return "[" + ", ".join(xs) + "]"


def main():
    import znumjudge as ZJ
    name = sys.argv[1] if len(sys.argv) > 1 else "circle_exp"
    spec = SYSTEMS[name]
    vs = spec["vars"]; d = len(vs)
    qs = ZJ.parse_quantities(", ".join(f"{v}=? credit" for v in vs))[0]
    trees = [ZJ._parse_arith(t, qs) for t in spec["laws"]]
    idx = {v: i for i, v in enumerate(vs)}
    Fs = [Z.to_xe(t, idx) for t in trees]
    Fn = lambda x: [fl(t, dict(zip(vs, x))) for t in trees]
    def J(x, h=1e-7):
        cols = []
        for j in range(d):
            xp = x[:]; xm = x[:]; xp[j] += h; xm[j] -= h
            fp, fm = Fn(xp), Fn(xm)
            cols.append([(a - b) / (2 * h) for a, b in zip(fp, fm)])
        return [[cols[j][i] for j in range(d)] for i in range(d)]
    x = list(spec["guess"])
    for _ in range(60):
        dx = solve(J(x), Fn(x))
        x = [a - b for a, b in zip(x, dx)]
    print("root", x, "residual", max(abs(v) for v in Fn(x)))
    Jx = J(x); Yf = inv(Jx)
    ys = [Z.floor_dy(F(v), 40) for v in x]
    Yd = [[Z.floor_dy(F(v), 30) for v in row] for row in Yf]
    Zd = [[Z.floor_dy(F(v), 30) for v in row] for row in Jx]
    r, rh, R, E = F(1, 1 << 20), F(1, 1 << 21), 30, 0
    nm = "ZSys" + "".join(p.capitalize() for p in name.split("_"))
    vnames = ", ".join(f"{v} = var {i}" for i, v in enumerate(vs))
    laws = "\n".join(f"    {t} = 0" for t in spec["laws"])
    text = f"""import ZKrawSys
/-!
# {nm} — {spec["title"]}: a solution on VR's continuum, and only one in its cube. Zero axioms. GENERATED by
`tools/zkraw2lean.py {name}`:

{laws}

Variables: {vnames}. The cube: centre ≈ ({", ".join(f"{v:.12g}" for v in x)}), radius 2⁻²⁰. The kernel checks the
Krawczyk certificate for `G = x − Y·F` and the invertibility of `Y` (`ZKrawSys.sys_root`).
-/

namespace {nm}
open ZNumBin ZIv ZXE ZRootExp ZRootDiv ZKraw ZKrawSys VR.Numbers ZRealCF

def Fs : Nat → XE := nthX {lst(Fs)}
def ys : List D := {lst([Z.dy(v) for v in ys])}
def Y : Nat → Nat → D := mat {lst([lst([Z.dy(v) for v in row]) for row in Yd])}
def Zm : Nat → Nat → D := mat {lst([lst([Z.dy(v) for v in row]) for row in Zd])}

/-- **THE SYSTEM HAS ITS SOLUTION, AND ONLY ONE IN THE CUBE.** -/
theorem solution : ∃ x : ZBanach.Vec, InC {d} ys {Z.dy(r)} x ∧ (∀ i, i < {d} → rEq (evR (trunc {d} x) (Fs i)) rzero) ∧
    ∀ u, InC {d} ys {Z.dy(r)} u → (∀ i, i < {d} → rEq (evR (trunc {d} u) (Fs i)) rzero) → ∀ i, i < {d} → rEq (u i) (x i) :=
  sys_root (d := {d}) (Y := Y) (Fs := Fs) (ys := ys) (r := {Z.dy(r)}) (rh := {Z.dy(rh)}) (R := {R}) (E := {E}) (Z := Zm) (by decide +kernel) (by decide +kernel)

/-- The fork's other side: a cube displaced by 2⁻¹⁰ (no solution inside) is refused. -/
example : chkK {d} {lst([Z.dy(v + F(1, 1024)) for v in ys])} {Z.dy(r)} {Z.dy(rh)} {R} {E} (Gsys {d} Y Fs) = false := by decide +kernel

end {nm}

#print axioms {nm}.solution
"""
    with open(os.path.join(LEAN, nm + ".lean"), "w") as f:
        f.write(text)
    print("wrote", nm)


if __name__ == "__main__":
    main()

# -*- coding: utf-8 -*-
"""Квитанция вердикта — наименьшая привязка, переживающая передачу.

НАРЯД. внешний рецензент, MAM-ZTL §13 D2: «наименьшая дополнительная привязка, при
которой объект памяти сохраняет зависимости от источника, допуска, TCC и ZTL
через ХРАНЕНИЕ и ПЕРЕДАЧУ».

ПОЧЕМУ ЭТО ВООБЩЕ НУЖНО (найдено разбором D1, 2026-08-28). У MAM цепь
хранения криптографическая: `SessionMAP` несёт корень Меркла, подпись и
идентификатор ключа. Наш судья отдаёт словарь. Пока у вердикта нет
канонического байтового вида и отпечатка, он войдёт в их лист Меркла только
непрозрачным комком — то есть после передачи его нельзя ПРОВЕРИТЬ, а можно
лишь пересказать. Это и есть недостающее звено, названное там же.

ПОЧЕМУ ИМЕННО КВИТАНЦИЯ, А НЕ ВСЯ РАЗМЕТКА — и это ТЕОРЕМА, а не уговор.
`lean/Receipt.lean` (ноль аксиом) доказывает `receipt_complete`: если атом не
назван в квитанции, его изменение НЕ МЕНЯЕТ ответа. Контрапозиция и есть то,
что нам нужно: **атом, способный перевернуть вердикт, всегда назван**. Значит
носить документ целиком не требуется — держащих атомов достаточно, и это
доказано, а не сочтено разумным.

ЧТО НЕСЁТ КВИТАНЦИЯ — ровно пять вещей, и каждая входит в отпечаток:
  1. `claim`      — что судили, канонически;
  2. `holding`    — на чём держится: имена и метки НЕСУЩИХ атомов (теорема
                    выше говорит, что этого достаточно);
  3. `verdict`    — вердикт, гарантия и погашаемость (`UNREDEEMABLE`, если
                    имя сидит в мёртвом кольце — иначе «проверьте позже»
                    остаётся ложным обещанием, см. zfl2.unredeemable);
  4. `epoch`      — эпоха, в которой вердикт вынесен: чужая эпоха не даёт
                    права переиспользовать (тот же инвариант, что в
                    `introspect/admission.py`, G6);
  5. `expiry`     — события, при которых основание истекает, из колонки
                    `expires_on`. У MAM этого понятия нет вовсе (в их
                    репозитории слова «epoch» ноль вхождений, срок годности
                    ни с чем не сравнивается) — значит носить его должны мы.

ЧЕГО КВИТАНЦИЯ НЕ ДЕЛАЕТ, сказано здесь, чтобы не пришлось узнавать потом:
она не подписывает (подпись — ключи потребителя, не наше дело), не
устанавливает истину источника (только что ФОРСИТ разметка) и не переносит
полномочие: предъявитель квитанции не получает права действовать, он получает
право ПРОВЕРИТЬ, что вердикт тот самый.
"""
from __future__ import annotations
import hashlib
import json

RECEIPT_VERSION = "warrant-receipt-0.1"


def _canon(obj) -> str:
    """Один байтовый вид на один смысл: сортировка ключей, без ASCII-эскейпов,
    без пробелов. Иначе два одинаковых вердикта дадут разные отпечатки и
    сверка после передачи станет невозможной."""
    return json.dumps(obj, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":"))


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def receipt(report: dict, doc: dict, epoch: str,
            ground_registry=None, derived_from=None) -> dict:
    """Квитанция из отчёта `zfl2.run` и документа, что его породил.

    `epoch` задаёт вызывающий: это не свойство вердикта, а состояние мира, в
    котором он вынесен, и подделать его изнутри нельзя.

    ПОЧЕМУ ПОЯВИЛСЯ `ground_registry` — дыра найдена ПРОГОНОМ в тот же день
    (2026-08-28), после того как arXiv 2606.24322 доказал машинно, что
    привязка происхождения нужна НА ЗАПИСИ, а защита по содержимому или по
    происхождению при отмывании несостоятельна. Проверил не рассуждением, а
    судьёй, по слову куратора («ZTL не интуитивен»):

        изготовил документ, где то же утверждение стоит на выдуманных
        основаниях «ЧТО-УГОДНО» и «ТОЖЕ-ЧТО-УГОДНО» — и квитанция с него
        сверилась ЧИСТО, неся `T EARNED hereditary`.

    Отпечаток связывает квитанцию САМУ С СОБОЙ и ничего не говорит о мире:
    он ловит ПОДМЕНУ, но не ЛОЖЬ ПРИ ИЗГОТОВЛЕНИИ. Теорема `receipt_complete`
    тут не помогает — она о ВЕРНОЙ квитанции и молчит о лживой.

    Лекарство нашлось своё же и вчерашнее — ворота оснований. Промерено на
    том же документе: с реестром вердикт падает с `T EARNED hereditary` до
    `Z OPEN until-verification`, а оба выдуманных основания разжалованы
    ПОИМЁННО; честный документ под тем же реестром зарабатывает как прежде.

    Реестр входит в отпечаток отдельным полем, и квитанция, выписанная БЕЗ
    реестра, теперь ОТЛИЧИМА от выписанной под реестром — это сигнал
    предъявителю, а не молчание."""
    judge = (report.get("report") or {}).get("judge") or {}
    rows = {r.get("name"): r for r in (doc.get("rows") or [])}
    holding = {}
    for name in sorted(judge.get("unverified") or []):
        holding[name] = "Z"
    # НЕСУЩИЕ — это не только непроверенные. Заработавшие имена, на которые
    # утверждение опирается, тоже держат его: отзови основание, и вердикт
    # поедет. Поэтому в квитанцию идут и они, с их основаниями.
    grounds = {}
    for name, r in sorted(rows.items()):
        if r.get("status") in ("verified", "refuted"):
            grounds[name] = {"status": r["status"],
                             "ground": (r.get("ground") or "").strip()}
    expiry = {name: (r.get("expires_on") or "").strip()
              for name, r in sorted(rows.items())
              if (r.get("expires_on") or "").strip()}
    reg = (None if ground_registry is None
           else {"digest": _sha(_canon(sorted(ground_registry))),
                 "size": len(set(ground_registry))})
    # ПРЕДКИ ВХОДЯТ В ОТПЕЧАТОК — иначе подмена предка не заметна, и вся
    # цепь стоит на честном слове. Записывается отпечаток предка И его
    # расположение на момент выдачи: без второго нельзя отличить «предка
    # подменили» от «предок сам упал», а это разные болезни.
    anc = None
    if derived_from:
        anc = {имя: {"digest": r["digest"],
                     "disposition": r["verdict"]["disposition"]}
               for имя, r in sorted(derived_from.items())}
    # ЭПОХА НЕОБЪЯВЛЕННАЯ — это НЕ пустая строка, а честный null, как и
    # реестр. Пустая строка молчит; null говорит «этого мне не сказали».
    # Слово куратора 2026-08-28: выдавать квитанцию ВСЕГДА, а нехватку
    # ПОМЕЧАТЬ — предъявитель тогда видит, чего ей недостаёт, вместо того
    # чтобы не иметь квитанции вовсе.
    core = {
        "version": RECEIPT_VERSION,
        "registry": reg,
        "derived_from": anc,
        "claim": (doc.get("claim") or "").strip(),
        "holding": holding,
        "grounds": grounds,
        "verdict": {"value": judge.get("verdict"),
                    "disposition": judge.get("disposition"),
                    "grade": judge.get("grade"),
                    "credit": judge.get("credit", "REDEEMABLE"),
                    "unredeemable": sorted(judge.get("unredeemable") or [])},
        "epoch": (epoch or None),
        "expiry": expiry,
    }
    return {**core, "digest": _sha(_canon(core))}


def verify_descent(rec: dict, ancestors_now: dict, _seen=None) -> dict:
    """Стоит ли ещё ПОТОМОК, когда предков перевыписали.

    ЧЕГО НЕТ НИ У КОГО (проверено D1 и D6, 2026-08-28): каскада отзыва по
    потомкам. У MAM связи «эта память произошла из той» нет ВОВСЕ — ни поля,
    ни свёртки; их собственная батарея D3 половиной векторов бьёт в пустоту.
    У arXiv 2606.24322 привязка строго НА ЗАПИСИ и по происхождению, и их
    текст прямо не рассматривает, годен ли вывод ПОСЛЕ отзыва основания.
    MemLineage несёт граф происхождения, но отказывает по тому, ОТКУДА
    пришло, а не по тому, СТОИТ ЛИ ЕЩЁ.

    Здесь третье: потомок падает, если предок ПЕРЕСТАЛ СТОЯТЬ. Не «пришёл из
    плохого места» — а «то, на чём он держался, больше не держит».

    `ancestors_now` — текущие квитанции предков по их именам. Возвращает
    verdict STANDS / FALLEN и ПРИЧИНУ по каждому павшему предку, потому что
    «упал» без причины — это то же молчание, против которого всё строится."""
    записано = rec.get("derived_from") or {}
    if not записано:
        return {"verdict": "STANDS", "why": "предков не объявлено"}
    # ПЕТЛЯ В ЦЕПИ — не гипотеза: `derived_from` заполняет вызывающий, и
    # квитанция, назвавшая предком себя, увела бы обход в бесконечность.
    # Отказ, а не переполнение стека: неразрешимую цепь надо НАЗВАТЬ.
    _seen = set(_seen or ())
    if rec["digest"] in _seen:
        return {"verdict": "FALLEN",
                "broken": [{"ancestor": "(сам)", "reason": "ANCESTOR_CYCLE"}]}
    _seen.add(rec["digest"])
    беды = []
    for имя, было in sorted(записано.items()):
        сейчас = ancestors_now.get(имя)
        if сейчас is None:
            беды.append({"ancestor": имя, "reason": "ANCESTOR_MISSING"})
            continue
        if not verify(сейчас):
            беды.append({"ancestor": имя, "reason": "ANCESTOR_TAMPERED"})
            continue
        if сейчас["digest"] != было["digest"]:
            # ДВЕ РАЗНЫЕ БОЛЕЗНИ ПОД ОДНИМ СИМПТОМОМ, и путать их нельзя:
            # предка ПОДМЕНИЛИ (расположение то же, отпечаток другой) — это
            # атака; предок ПАЛ (расположение уехало) — это жизнь.
            то_же = (сейчас["verdict"]["disposition"] == было["disposition"])
            беды.append({"ancestor": имя,
                         "reason": "ANCESTOR_SUBSTITUTED" if то_же
                                   else "ANCESTOR_FELL",
                         "was": было["disposition"],
                         "now": сейчас["verdict"]["disposition"]})
            continue
        # ТРАНЗИТИВНО. Предок цел и не двигался — но мог пасть ПО СВОЕЙ цепи,
        # и тогда потомок «выглядит чисто» при негодном прародителе. Это
        # ровно вектор D3 №12 из наряда внешнего рецензента, и одноуровневая проверка
        # его НЕ ЛОВИТ — промерено на деде-отце-внуке 2026-08-28.
        глубже = verify_descent(сейчас, ancestors_now, _seen)
        if глубже["verdict"] == "FALLEN":
            беды.append({"ancestor": имя, "reason": "ANCESTOR_CHAIN_BROKEN",
                         "under": глубже["broken"]})
    if not беды:
        return {"verdict": "STANDS", "ancestors": sorted(записано)}
    return {"verdict": "FALLEN", "broken": беды}


def verify(rec: dict) -> bool:
    """Та же проверка, что у сертификата допуска: пересчитать и сверить.
    Изменение ЛЮБОГО из пяти полей меняет отпечаток и валит сверку."""
    core = {k: v for k, v in rec.items() if k != "digest"}
    return rec.get("digest") == _sha(_canon(core))

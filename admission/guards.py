# ══ ТИПИЗИРОВАННОЕ СОХРАНЕНИЕ (TCC): не только сторож ═══════════════════════
# Найдено АТАКОЙ НА СЕБЯ 2026-08-26 (ztl-private/guard-probe/attack_tcc.py).
# Куратор поставил диагноз строже моего: «если не детерминировано, то не важно
# насколько». Я подал 27 ложных допусков как ДОЛЮ — будто есть механизм с
# погрешностью. Проверка кода показала: правила про модальность, актора и
# числовые границы НЕ БЫЛО ВОВСЕ. Значит покрытие равно НУЛЮ, а проценты
# бессмысленны: 392 непрошедших случая не были пойманы — они упёрлись в
# молчание разъёма, потому что указателя рядом не оказалось.
#
# УРОК ИЗ ЧУЖОГО КОДА (P2T, промерено на их выгрузках): типизированное поле в
# схеме НЕ РАВНО заполненному. У них `exceptions` обязательно и заполнено в
# 0.5 % из 2462 правил. Потому здесь каждый тип не «поле», а ПРАВИЛО, которое
# либо срабатывает, либо честно молчит.
#
# ПРАВО ТИПОВ: каждый вправе ЗАПРЕТИТЬ и НЕ вправе разрешить. CLEAR по-прежнему
# даёт только разъём — теперь ДОПОЛНИТЕЛЬНО к прохождению всех типов.

_MODAL = {"must": "ОБЯЗАН", "shall": "ОБЯЗАН", "required": "ОБЯЗАН",
          "may": "ВПРАВЕ", "can": "ВПРАВЕ", "permitted": "ВПРАВЕ", "entitled": "ВПРАВЕ"}
_MRX_MODAL = re.compile(r"\b(" + "|".join(_MODAL) + r")\b", re.I)
_NEG_MODAL = re.compile(r"\b(?:shall|must|may|can)\s+not\b|\bno\s+\w+\s+(?:shall|may|must)\b|"
                        r"\bnot\s+(?:be\s+)?(?:required|permitted|entitled)\b", re.I)
# «не более 30 дней» против «не менее 30 дней» — направление решает всё
# МЕЖДУ ПРЕДЛОГОМ И ЧИСЛОМ БЫВАЮТ СЛОВА. Первая редакция требовала числа сразу
# после сравнителя и потому не видела «within THE PERIOD OF 6 months» — на этом
# единственный ложный допуск и уцелел из двадцати семи (Закон о защите данных,
# срок упрощённого производства). Промерено, а не предположено: у обеих сторон
# границы выходили пустыми, и правилу нечего было сравнивать.
# «up to 30 days» НЕ ВИДЕЛОСЬ ВОВСЕ (промерено 2026-08-28: bounds() на
# «may retain for up to 30 days» возвращал пусто). Это ходовой оборот
# разрешений, и его отсутствие делало правило слепым ровно там, где ниже
# оказалось, что оно к тому же и перевёрнуто.
_BOUND = re.compile(r"\b(not exceeding|no more than|at most|within|not later than|"
                    r"up to|"
                    r"not less than|at least|no fewer than|exceeding|more than|"
                    r"less than|fewer than|longer than|shorter than)\b"
                    r"(?:\s+(?:the|a|an|period|of|more|less|than)){0,4}\s+"
                    r"(\d{1,5})\s*"
                    r"(days?|months?|years?|weeks?|hours?|per ?cent|%)?", re.I)
_ВЕРХ = {"not exceeding", "no more than", "at most", "within", "not later than",
         "up to",
         "less than", "fewer than", "shorter than"}
_ШУМ = set("the a an of to in and or for by with on at as is are be shall not this that which "
           "such any all from under may must can it its their his her they he she we you".split())


def modality(text: str) -> set:
    """Деонтический род: ОБЯЗАН / ВПРАВЕ. Лексика, без модели."""
    return {_MODAL[m.group(1).lower()] for m in _MRX_MODAL.finditer(text or "")}


def polarity_negations(text: str) -> int:
    """Сколько отрицаемых модальностей. Переворот полярности меняет это число."""
    return len(_NEG_MODAL.findall(text or ""))


def bounds(text: str) -> list:
    """Числовые границы С НАПРАВЛЕНИЕМ. «не более 30» и «не менее 30» — разное."""
    out = []
    for m in _BOUND.finditer(text or ""):
        comp = " ".join(m.group(1).lower().split())
        out.append(("ВЕРХ" if comp in _ВЕРХ else "НИЗ", int(m.group(2)),
                    (m.group(3) or "").lower().rstrip("s")))
    return out


_ACTOR_WIDE = re.compile(r"\b(any person|anyone|any individual|any body|whoever|"
                         r"any party|a person|any entity)\b", re.I)


def actor_widened(source: str, claim: str) -> bool:
    """Появился ли в утверждении РАСШИРЯЮЩИЙ актор, которого нет в источнике."""
    в_к = set(m.group(0).lower() for m in _ACTOR_WIDE.finditer(claim or ""))
    в_и = set(m.group(0).lower() for m in _ACTOR_WIDE.finditer(source or ""))
    return bool(в_к - в_и)


def invented_content(source: str, claim: str, порог: int = 3) -> list:
    """Знаменательные слова утверждения, которых НЕТ в источнике.

    Обязательный опровергатель по слову владельца: кандидат ничего не роняет, но
    ДОБАВЛЯЕТ положение, которого источник не содержит. Порог отсекает шум
    перефразировки; полностью от него не спасает, и это заявленный предел."""
    ии = set(w.lower() for w in re.findall(r"\w+", source or "") if len(w) > 3)
    нов = [w for w in re.findall(r"\w+", claim or "")
           if len(w) > 3 and w.lower() not in ии and w.lower() not in _ШУМ]
    return нов if len(нов) >= порог else []


# ТОЧНЫЙ СРОК — не граница с направлением. «the period of 6 months» ничего не
# ограничивает сверху или снизу: это ИМЕННО СТОЛЬКО. Удвоение меняет норму в
# любую сторону, и сравнивать надо на РАВЕНСТВО, а не на невыход за предел.
# Найдено разбором оставшихся 87 молчаний: 37 из них — ровно этот оборот.
_КОЛ = re.compile(r"\b(?:period|term|interval|duration)\s+of\s+(\d{1,5})\s*"
                  r"(days?|months?|years?|weeks?|hours?)\b", re.I)


def exact_quantities(text: str) -> set:
    """Точные величины: (число, единица). Сохраняются РАВЕНСТВОМ, не пределом."""
    return {(int(m.group(1)), m.group(2).lower().rstrip("s"))
            for m in _КОЛ.finditer(text or "")}


# ══ TCC-2: ОТНОШЕНИЕ ЗАМЕНЫ И ГДЕ ОНО ПЕРЕВОРАЧИВАЕТСЯ ═════════════════════
# Наряд внешнего рецензента TCC-2: «наименьшее отношение для случаев вида R ⇒ Q, и ровно
# какие типы предложений переворачивают направление. Универсального порядка не
# заводить, если не можешь его доказать.»
#
# ОТВЕТ, И ОН ОТРИЦАТЕЛЬНЫЙ ПО ФОРМЕ: универсального порядка НЕТ, и не потому
# что мы его не нашли. «Консервативно» не имеет смысла без ответа на вопрос ДЛЯ
# КОГО. Одна и та же синтаксическая правка — сузить срок с 30 до 14 — читается
# противоположно в зависимости от того, кого норма защищает:
#
#   ОБЯЗАН (обязанность на адресате, защищает КОНТРАГЕНТА):
#       сузить срок = обязанность строже = контрагенту НЕ ХУЖЕ = сохранено;
#       расширить    = обязанность слабее = контрагент ТЕРЯЕТ  = нарушение.
#   ВПРАВЕ (право у адресата, защищает САМОГО АДРЕСАТА):
#       сузить срок = права МЕНЬШЕ = адресат ТЕРЯЕТ = НАРУШЕНИЕ;
#       расширить    = права больше = адресату не хуже = сохранено.
#
# То есть переворачивает направление ДЕОНТИЧЕСКИЙ ТИП, и он один: не актор, не
# единица, не величина. Полярность переворачивает второй раз (запрет есть
# обязанность НЕ делать), поэтому она учитывается отдельным множителем.
#
# ЗАЧЕМ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ПРАВКА conserve_types: старое правило
# считает сужение безопасным ВСЕГДА. Промерено 2026-08-28 на паре «право
# сузили с 30 до 14 дней» — МОЛЧАНИЕ, при том что у правообладателя отняли
# половину окна; и на паре «право расширили до 60» — оно кричит «РАСШИРЕНА»,
# хотя правообладателю стало лучше. Для разрешений оно перевёрнуто в ОБЕ
# стороны. Менять его поведение молча нельзя — на нём стоят стенды и разъём
# CLEAR, поэтому здесь новое имя, а решение о замене — куратора.

_БЕНЕФИЦИАР = {"ОБЯЗАН": "контрагент", "ВПРАВЕ": "адресат"}


def replacement_direction(deontic: str, negations: int) -> int:
    """+1 если СУЖЕНИЕ верхней границы сохраняет, -1 если ОТНИМАЕТ, 0 если тип
    не определён и правило обязано молчать.

    Отрицание переворачивает: «не вправе более 30 дней» есть обязанность."""
    base = {"ОБЯЗАН": +1, "ВПРАВЕ": -1}.get(deontic, 0)
    return base * (-1 if negations % 2 else 1)


def conservative_replacement(source: str, claim: str) -> dict:
    """Отношение «claim честно заменяет source», НАИМЕНЬШЕЕ и с бенефициаром.

    Возвращает: verdict CONSERVATIVE / LOSS / SILENT, кто бенефициар, и по
    какой именно границе. SILENT — не «сохранено», а «типа не видно, права
    судить нет». Никакого универсального порядка тут не строится: без
    деонтического типа функция отказывается решать."""
    ми, мк = modality(source), modality(claim)
    if len(ми) != 1 or ми != мк:
        return {"verdict": "SILENT",
                "why": f"деонтический тип не определён однозначно: "
                       f"{sorted(ми)} → {sorted(мк)}"}
    вид = next(iter(ми))
    напр = replacement_direction(вид, polarity_negations(source))
    if напр == 0:
        return {"verdict": "SILENT", "why": "тип вне {ОБЯЗАН, ВПРАВЕ}"}
    би, бк = bounds(source), bounds(claim)
    находки = []
    # ОТРИЦАНИЕ ПЕРЕВОРАЧИВАЕТ ДВАЖДЫ, и вторую половину я сначала упустил —
    # нашлось прогоном собственной батареи (2026-08-28, случай «may not retain
    # more than 30 days» → «more than 14»). Лексически «more than» это НИЖНЯЯ
    # граница, но под запретом действующий предел ВЕРХНИЙ: запретить всё сверх
    # 14 строже, чем запретить всё сверх 30. Значит под нечётным числом
    # отрицаний чтение границы меняется местами, отдельно от смены типа.
    отрицание = polarity_negations(source) % 2 == 1
    for (нап, зн, ед) in бк:
        пара = [x for x in би if x[0] == нап and x[2] == ед]
        if not пара:
            continue
        ши = пара[0][1]
        if зн == ши:
            continue
        чтение = ("НИЗ" if нап == "ВЕРХ" else "ВЕРХ") if отрицание else нап
        # сузили верхнюю границу или подняли нижнюю — «строже»
        строже = (зн < ши) if чтение == "ВЕРХ" else (зн > ши)
        сохранено = строже if напр > 0 else not строже
        находки.append({
            "bound": f"{нап} {ши}{ед} → {зн}{ед}",
            "stricter": строже,
            "verdict": "CONSERVATIVE" if сохранено else "LOSS"})
    if not находки:
        return {"verdict": "SILENT", "deontic": вид,
                "why": "сравнимых границ не нашлось"}
    verdict = "LOSS" if any(f["verdict"] == "LOSS" for f in находки) \
        else "CONSERVATIVE"
    # Под запретом защищаемая сторона тоже меняется: «вправе НЕ более» бережёт
    # не адресата, а того, против кого предел поставлен.
    бенеф = _БЕНЕФИЦИАР[вид] if not отрицание else (
        "контрагент" if вид == "ВПРАВЕ" else "адресат")
    return {"verdict": verdict, "deontic": вид,
            "beneficiary": бенеф,
            "direction": напр, "bounds": находки}


def conserve_types(source: str, claim: str) -> dict:
    """Проверка ТИПОВ. Возвращает список нарушений; пусто — значит не возразил.

    ПУСТО НЕ ОЗНАЧАЕТ «сохранено». Означает «эти правила не возразили».
    Разрешает по-прежнему только разъём."""
    v = []
    ми, мк = modality(source), modality(claim)
    if ми and мк and ми != мк:
        v.append(("модальность", f"{sorted(ми)} → {sorted(мк)}"))
    ни, нк = polarity_negations(source), polarity_negations(claim)
    if ни != нк:
        v.append(("полярность", f"отрицаний {ни} → {нк}"))
    # ВЕТКА ГРАНИЦ ЗАМЕНЕНА НА ТИПИЗИРОВАННОЕ ОТНОШЕНИЕ (TCC-2, слово
    # куратора 2026-08-28 «если оно лучше — меняем»). Прежняя считала
    # СУЖЕНИЕ безопасным ВСЕГДА, то есть строила универсальный порядок, и для
    # РАЗРЕШЕНИЙ была перевёрнута в обе стороны: право сузили 30->14 — она
    # молчала, право расширили — кричала «расширена». Промерено.
    #
    # Заменена ТОЛЬКО эта ветка. Целиком новое отношение старое НЕ покрывает:
    # оно умеет границы, а модальность, полярность, точный срок, актора и
    # приписанное содержание — не умеет. Обменять пять проверок на одну
    # исправленную было бы ровно тем, за что мы браним чужой код.
    отн = conservative_replacement(source, claim)
    if отн["verdict"] == "LOSS":
        for f in отн["bounds"]:
            v.append(("числовая граница",
                      f"{f['bound']} — ПОТЕРЯ для {отн['beneficiary']} "
                      f"({отн['deontic']}, "
                      f"{'строже' if f['stricter'] else 'слабее'})"))
    elif отн["verdict"] == "SILENT":
        # Тип не определён — судить о направлении НЕ ВПРАВЕ. Возвращаемся к
        # прежней проверке: она груба, но молчание тут было бы хуже грубости.
        би, бк = bounds(source), bounds(claim)
        for (нап, зн, ед) in бк:
            пара = [x for x in би if x[0] == нап and x[2] == ед]
            if пара:
                ши = пара[0][1]
                if (нап == "ВЕРХ" and зн > ши) or (нап == "НИЗ" and зн < ши):
                    v.append(("числовая граница",
                              f"{нап} {ши}{ед} → {зн}{ед} — РАСШИРЕНА "
                              f"(тип не определён, судим грубо)"))
    ки, кк = exact_quantities(source), exact_quantities(claim)
    for (зн, ед) in кк:
        свои = [x for x in ки if x[1] == ед]
        if свои and зн not in {x[0] for x in свои}:
            v.append(("точный срок", f"{sorted(x[0] for x in свои)}{ед} → {зн}{ед} — ИЗМЕНЁН"))
    if actor_widened(source, claim):
        v.append(("актор", "введён расширяющий актор, которого нет в источнике"))
    # ПРИРОСТ ОБЪЁМА ЕСТЬ ДОБАВЛЕНИЕ. Порог по НОВЫМ словам оказался дырявым:
    # приписка «and any other measure applies» к клаузе, где уже есть «any other
    # processors», даёт всего ДВА новых слова и проходила порог в три. Промерено
    # 2026-08-26 на живом раскладе — один ложный допуск из 1379.
    # Счёт знаменательных слов обмануть так нельзя: приписали — стало больше.
    _зн = lambda t: [w for w in re.findall(r"\w+", t or "")
                     if w.lower().isdigit() or (len(w) > 2 and w.lower() not in _ШУМ)]
    ди, дк = len(_зн(source)), len(_зн(claim))
    if дк > ди:
        v.append(("добавлено содержание", f"знаменательных слов {ди} → {дк}"))
    нов = invented_content(source, claim)
    if нов:
        v.append(("выдуманное", f"слов вне источника: {len(нов)} — {нов[:6]}"))
    return {"violations": v, "ok": not v}

# -*- coding: utf-8 -*-
"""Квитанция вердикта — наименьшая привязка, переживающая передачу.

НАРЯД. внешний рецензент, MAM-ZTL §13 D2: «наименьшая дополнительная привязка, при
которой объект памяти сохраняет зависимости от источника, допуска, TCC и ZTL
через ХРАНЕНИЕ и ПЕРЕДАЧУ».

ПОЧЕМУ ЭТО ВООБЩЕ НУЖНО (найдено разбором D1, 2026-08-28). У MAM цепь
хранения криптографическая: `SessionMAP` несёт корень Меркла, подпись и
идентификатор ключа. Наш судья отдаёт словарь. Пока у вердикта нет
канонического байтового вида и отпечатка, он войдёт в их лист Меркла только
непрозрачным комком — то есть после передачи его нельзя ПРОВЕРИТЬ, а можно
лишь пересказать. Это и есть недостающее звено, названное там же.

ПОЧЕМУ ИМЕННО КВИТАНЦИЯ, А НЕ ВСЯ РАЗМЕТКА — и это ТЕОРЕМА, а не уговор.
`lean/Receipt.lean` (ноль аксиом) доказывает `receipt_complete`: если атом не
назван в квитанции, его изменение НЕ МЕНЯЕТ ответа. Контрапозиция и есть то,
что нам нужно: **атом, способный перевернуть вердикт, всегда назван**. Значит
носить документ целиком не требуется — держащих атомов достаточно, и это
доказано, а не сочтено разумным.

ЧТО НЕСЁТ КВИТАНЦИЯ — ровно пять вещей, и каждая входит в отпечаток:
  1. `claim`      — что судили, канонически;
  2. `holding`    — на чём держится: имена и метки НЕСУЩИХ атомов (теорема
                    выше говорит, что этого достаточно);
  3. `verdict`    — вердикт, гарантия и погашаемость (`UNREDEEMABLE`, если
                    имя сидит в мёртвом кольце — иначе «проверьте позже»
                    остаётся ложным обещанием, см. zfl2.unredeemable);
  4. `epoch`      — эпоха, в которой вердикт вынесен: чужая эпоха не даёт
                    права переиспользовать (тот же инвариант, что в
                    `introspect/admission.py`, G6);
  5. `expiry`     — события, при которых основание истекает, из колонки
                    `expires_on`. У MAM этого понятия нет вовсе (в их
                    репозитории слова «epoch» ноль вхождений, срок годности
                    ни с чем не сравнивается) — значит носить его должны мы.

ЧЕГО КВИТАНЦИЯ НЕ ДЕЛАЕТ, сказано здесь, чтобы не пришлось узнавать потом:
она не подписывает (подпись — ключи потребителя, не наше дело), не
устанавливает истину источника (только что ФОРСИТ разметка) и не переносит
полномочие: предъявитель квитанции не получает права действовать, он получает
право ПРОВЕРИТЬ, что вердикт тот самый.
"""
from __future__ import annotations
import hashlib
import json

RECEIPT_VERSION = "warrant-receipt-0.1"


def _canon(obj) -> str:
    """Один байтовый вид на один смысл: сортировка ключей, без ASCII-эскейпов,
    без пробелов. Иначе два одинаковых вердикта дадут разные отпечатки и
    сверка после передачи станет невозможной."""
    return json.dumps(obj, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":"))


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def receipt(report: dict, doc: dict, epoch: str) -> dict:
    """Квитанция из отчёта `zfl2.run` и документа, что его породил.

    `epoch` задаёт вызывающий: это не свойство вердикта, а состояние мира, в
    котором он вынесен, и подделать его изнутри нельзя."""
    judge = (report.get("report") or {}).get("judge") or {}
    rows = {r.get("name"): r for r in (doc.get("rows") or [])}
    holding = {}
    for name in sorted(judge.get("unverified") or []):
        holding[name] = "Z"
    # НЕСУЩИЕ — это не только непроверенные. Заработавшие имена, на которые
    # утверждение опирается, тоже держат его: отзови основание, и вердикт
    # поедет. Поэтому в квитанцию идут и они, с их основаниями.
    grounds = {}
    for name, r in sorted(rows.items()):
        if r.get("status") in ("verified", "refuted"):
            grounds[name] = {"status": r["status"],
                             "ground": (r.get("ground") or "").strip()}
    expiry = {name: (r.get("expires_on") or "").strip()
              for name, r in sorted(rows.items())
              if (r.get("expires_on") or "").strip()}
    core = {
        "version": RECEIPT_VERSION,
        "claim": (doc.get("claim") or "").strip(),
        "holding": holding,
        "grounds": grounds,
        "verdict": {"value": judge.get("verdict"),
                    "disposition": judge.get("disposition"),
                    "grade": judge.get("grade"),
                    "credit": judge.get("credit", "REDEEMABLE"),
                    "unredeemable": sorted(judge.get("unredeemable") or [])},
        "epoch": epoch,
        "expiry": expiry,
    }
    return {**core, "digest": _sha(_canon(core))}


def verify(rec: dict) -> bool:
    """Та же проверка, что у сертификата допуска: пересчитать и сверить.
    Изменение ЛЮБОГО из пяти полей меняет отпечаток и валит сверку."""
    core = {k: v for k, v in rec.items() if k != "digest"}
    return rec.get("digest") == _sha(_canon(core))

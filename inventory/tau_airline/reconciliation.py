    print("  сходится с 0 из 104")

    # ПРОВЕРКА, которую легко пропустить
    tree = ast.parse(open(os.path.join(HERE, "tasks_airline.py"), encoding="utf-8").read())
    tasks = next(n.value.elts for n in ast.walk(tree)
                 if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "TASKS")
    both = cancel_only = 0
    NEEDS_USER = {"send_certificate", "book_reservation"}
    for t in tasks:
        names = []
        for node in ast.walk(t):
            if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "Action":
                for kw in node.keywords:
                    if kw.arg == "name":
                        names.append(ast.literal_eval(kw.value))
        if "cancel_reservation" in names:
            if set(names) & NEEDS_USER:
                both += 1
            else:
                cancel_only += 1

    print("\n" + "=" * 68)
    print("ОПУСКАЕМОСТЬ get_user_details — ПРОВЕРКА ПО ЗАДАЧАМ")
    print("=" * 68)

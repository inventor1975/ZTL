# ЧАНКИНГ — промерен 2026-08-23 (см. память project_atom_notebook_experiment). Целый
# длинный текст судье не по зубам за раз; чанки — способ досчитать. Режем по
# ЕСТЕСТВЕННЫМ швам (заголовки/границы абзацев), НИКОГДА не поперёк абзаца: на
# ценностной оси рамка И ЕСТЬ суждение, и край куска пере-обрамляет пограничные T?/T.
def chunk_prose(text: str, target_lines: int = 50) -> list[tuple[str, str]]:
    """Резать прозу по швам: копим абзацы до target_lines непустых строк, заголовок
    верхнего уровня (# …) открывает новый чанк. Возвращает [(метка-зачин, текст)]."""
    paras = [p for p in text.split("\n\n") if p.strip()]
    chunks: list[str] = []
    cur: list[str] = []
    cnt = 0
    for p in paras:
        stripped = p.lstrip()
        is_top = stripped.startswith("# ") or stripped.rstrip() == "#"
        if is_top and cur:
            chunks.append("\n\n".join(cur)); cur, cnt = [], 0
        cur.append(p); cnt += p.count("\n") + 1
        if cnt >= target_lines and not is_top:
            chunks.append("\n\n".join(cur)); cur, cnt = [], 0
    if cur:
        chunks.append("\n\n".join(cur))
    out = []
    for c in chunks:
        first = next((ln.strip() for ln in c.splitlines() if ln.strip()), "")
        out.append((first[:60], c))
    return out


def prepare(text: str, out_dir: pathlib.Path, target_lines: int = 50,
            genre: str = "") -> list[pathlib.Path]:
    """Нарезать текст и написать по task'у на кусок (рубрика+кусок). Судья — форк/я,
    НЕ ключ. Возвращает пути task'ов; печатает тэлл и как потреблять (форк/сам)."""
    chunks = chunk_prose(text, target_lines)
    out_dir.mkdir(parents=True, exist_ok=True)
    tasks = []
    for i, (label, ctext) in enumerate(chunks, 1):
        tell = absolute_flags(ctext)
        tell_block = ""
        if tell:
            tell_block = ("\n\n<!-- ТЭЛЛ АБСОЛЮТА (наводка, не вердикт):\n"
                          + "\n".join(f"  {t}" for t in tell) + "\n-->")
        # Жанр — ЗАПАСНОЙ ход рубрики: он ВНЕШНИЙ, из куска не читается. Кто
        # текст подаёт, тот жанр и знает; не объявлен — судья обязан объявить
        # развилку, а не выбрать за нас (см. REGISTER).
        genre_block = (f"\n\nЖАНР ТЕКСТА ОБЪЯВЛЕН: {genre}"
                       if genre else
                       "\n\nЖАНР ТЕКСТА НЕ ОБЪЯВЛЕН — где метка от него зависит, "
                       "объявляй развилку, не гадай.")
        body = (f"<!-- task {i:02d} — {label} -->\n\n"
                + RUBRIC.format(text=ctext) + genre_block + tell_block)
        p = out_dir / f"task-{i:02d}.md"
        p.write_text(body, encoding="utf-8")
        tasks.append(p)
    n = len(tasks)
    print(f"подготовлено {n} task'ов в {out_dir}", file=sys.stderr)
    if n == 1:
        print("  → 1 кусок: СУДИ САМ в своём контексте (форк ради абзаца — лишнее).",
              file=sys.stderr)
    else:
        print(f"  → {n} кусков: раздай ФОРКАМ (по субагенту на task, параллельно) или суди подряд сам;",
              file=sys.stderr)
        print("    каждый вердикт положи в verdicts/verdict-NN.md, потом `assemble verdicts/`.",
              file=sys.stderr)
    return tasks


def assemble(verdicts_dir: pathlib.Path, out: pathlib.Path, source_name: str = "") -> pathlib.Path:
    """Сшить вердикты (verdict-NN.md, судья — форк/я) в единый credit-ledger."""
    files = sorted(verdicts_dir.glob("verdict-*.md"))
    if not files:
        sys.exit(f"нет вердиктов в {verdicts_dir} (ждём verdict-NN.md)")
    body = "\n\n".join(f.read_text(encoding="utf-8").strip() for f in files)
    # Считаем метки ТОЛЬКО на строках-атомах (буллет «- …»), не в прозе ВЫБОРа —
    # иначе повтор метки в выборе задваивает счёт (S=2 атома читались как 4).
    counts = {}
    # КРАЙ РАМКИ — СЧИТАЕМ, А НЕ НАДЕЕМСЯ. Рубрика требует по каждому S и T?
    # назвать, ЧТО вынесено за край. Требование, которое никто не проверяет,
    # это пожелание: судья-форк забудет, и никто не заметит. Поэтому здесь
    # СЧЁТ, и он попадает в шапку ledger'а.
    #
    # ПОЧЕМУ НЕ ОТКАЗ. Соблазн, что по нашему же default-deny надо ОТКАЗАТЬ в
    # сборке. Но ledger — не допуск посылки, а лист для ЧЕЛОВЕКА: отказать
    # значит выбросить работу судьи из-за забытой фразы. Правило «не пропускать
    # молча» соблюдено громкой пометкой, а не потерей труда. Калибровка по цене
    # ошибки, а не по красоте принципа.
    # ХОД БЫВАЕТ МНОГОСТРОЧНЫМ. Сборщик читал буллет как ОДНУ строку, и судья,
    # который выносит «отрезано:» и «правило:» на продолжение с отступом, получал
    # ложное «не назвал». Промерено 2026-08-29 на перепрогоне крокодила: третий
    # судья назвал правило у КАЖДОГО хода, а счётчик отчитался «ни у одного»,
    # и я едва не записал это ему в дефект. Третий случай за день, когда мой
    # разбор строк чуть не стал чужой виной.
    #
    # Продолжение — непустая строка С ОТСТУПОМ. Пустая строка ход закрывает,
    # неотступленная проза в ход НЕ втягивается (иначе «правило:» из соседнего
    # абзаца зачлось бы этому ходу).
    def _ходы(текст: str):
        cur: list[str] | None = None
        for ln in текст.splitlines():
            if re.match(r"\s*[-*]\s", ln) and not ln.startswith((" ", "\t")):
                if cur is not None:
                    yield " ".join(cur)
                cur = [ln]
            elif cur is not None and ln.strip() and ln[:1] in (" ", "\t"):
                cur.append(ln.strip())
            elif cur is not None:
                yield " ".join(cur); cur = None
        if cur is not None:
            yield " ".join(cur)

    без_края = []
    # Развилка «[S|T? — зависит от жанра]» — законный ответ судьи по REGISTER, но
    # обычный счёт меток её НЕ ВИДИТ (в скобке два символа, а не один). Молчаливая
    # потеря здесь — худший исход: ход, где рубрика не решила, исчез бы из сводки,
    # и ledger отчитался бы полнотой, которой нет. Считаем и выносим в шапку.
    развилки = []
    # Развилка теперь по ЛЮБОЙ паре меток, не только S|T? и не только по жанру:
    # вынужденный выбор там, где ось не решена, даёт ложный шум (крокодил, 3/0/1).
    _FORK_RE = re.compile(r"\[\s*(?:T\?|[TSFZE])\s*\|\s*(?:T\?|[TSFZE])[^\]]*\]")
    # Правило, по которому поставлена метка. Считаем и его, и ЕГО ОТСУТСТВИЕ.
    _RULE_RE = re.compile(r"правило:\s*([А-Яа-яA-Za-z\-]+)")
    правила: dict[str, int] = {}
    без_правила = []
    for ln in _ходы(body):
        if True:
            # Развилку в СЧЁТ МЕТОК не берём (метки ещё нет — есть две), но КРАЙ
            # РАМКИ с неё спрашиваем: обе ветви развилки — S и T?, а край требуется
            # у обеих. Пропустить проверку здесь значило бы, что судья уходит от
            # улики, объявив развилку.
            метки: list[str] = []
            fork = bool(_FORK_RE.search(ln))
            if fork:
                развилки.append(ln.strip()[:70])
            else:
                метки = re.findall(r"\[(T\?|S|T|F|Z|E)\]", ln)
                for m in метки:
                    counts[m] = counts.get(m, 0) + 1
            if (fork or "S" in метки or "T?" in метки) and "отрезано:" not in ln:
                без_края.append(ln.strip()[:70])
            r = _RULE_RE.search(ln)
            if r:
                правила[r.group(1).lower()] = правила.get(r.group(1).lower(), 0) + 1
            else:
                без_правила.append(ln.strip()[:70])
    head = [f"# credit-ledger — {source_name or verdicts_dir.name}", "",
            "Ярус 3 (zchoose), судья — ФОРК/сам (без ключа). "
            "Метки: T доброе / T? уязвимое / S соблазн / F ложь / Z кредит / E не на чем.",
            f"Кусков: {len(files)}. Сводка меток: "
            + ("  ".join(f"{k}={v}" for k, v in sorted(counts.items())) or "—")
            + (f".  Развилок, где рубрика не решила: {len(развилки)}." if развилки else "."),
            ""]
    if развилки:
        head += [f"**РУБРИКА НЕ РЕШИЛА у {len(развилки)} ход(а/ов)** — судья объявил "
                 "развилку вместо догадки, как и требует рубрика. Закрывает её "
                 "ЧЕЛОВЕК: ответив на названный вопрос (например объявив жанр "
                 "через `prepare --genre …`) и пересудив кусок.", ""]
        head += [f"  - {s_}" for s_ in развилки[:10]] + [""]
    if без_края:
        head += [f"**КРАЙ РАМКИ НЕ НАЗВАН у {len(без_края)} ход(а/ов)** — рубрика "
                 "требует по каждому S и T? написать «отрезано: …», то есть кого "
                 "или что рамка вынесла за край. Без этого метка названа, а УЛИКА "
                 "нет: соблазн опознаётся не по выводу, а по обрезку.", ""]
        head += [f"  - {s}" for s in без_края[:10]] + [""]
    else:
        head += ["Край рамки назван у всех S и T?." if counts.get("S") or counts.get("T?")
                 else "Ходов S и T? нет — край рамки называть не у чего.", ""]
    # ПО КАКИМ ПРАВИЛАМ СУДИЛИ. Строка «нет-правила» дороже всех остальных:
    # это места, где рубрика молчит, и они и есть материал для следующей правки.
    if правила:
        head += ["Правила, по которым ставились метки: "
                 + "  ".join(f"{k}={v}" for k, v in sorted(правила.items())) + ".", ""]
        if правила.get("нет-правила"):
            head += [f"**«НЕТ-ПРАВИЛА» у {правила['нет-правила']} ход(а/ов)** — судья "
                     "честно сказал, что ни одно правило не подошло. Это НЕ брак "
                     "судьи, а место, где молчит рубрика; читать в первую очередь.", ""]
    if без_правила:
        head += [f"**ПРАВИЛО НЕ НАЗВАНО у {len(без_правила)} ход(а/ов)** — рубрика "
                 "требует называть его в каждой строке. Без имени расхождение судей "
                 "нельзя разложить на «разные метки» и «разные правила».", ""]
        head += [f"  - {s_}" for s_ in без_правила[:10]] + [""]
    head += ["---", ""]
    out.write_text("\n".join(head) + body + "\n", encoding="utf-8")
    print(f"ledger -> {out}  (кусков {len(files)}, метки { {k: counts[k] for k in counts} })",
          file=sys.stderr)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="ярус 3 БЕЗ КЛЮЧА: подготовить куски для форка/себя, сшить ledger")
    sub = ap.add_subparsers(dest="cmd", required=True)

    pp = sub.add_parser("prepare", help="нарезать текст на task'и (рубрика+кусок), судья — форк/я")
    pp.add_argument("target", help="текст-файл рассуждения")
    pp.add_argument("--out", default=None, help="куда класть task'и (по умолч. <файл>.tasks/)")
    pp.add_argument("--lines", type=int, default=50, dest="target_lines",
                    help="целевой размер куска в строках")
    pp.add_argument("--genre", default="", help="объявленный жанр текста (отчёт/разбор/"
                    "письмо/питч…) — запасной различитель T?/S, когда механизм не решает")

    pa = sub.add_parser("assemble", help="сшить вердикты форков/мои в credit-ledger")
    pa.add_argument("verdicts", help="папка с verdict-NN.md")
    pa.add_argument("--out", default=None, help="куда писать ledger")

    args = ap.parse_args()

    if args.cmd == "prepare":
        target = pathlib.Path(args.target).resolve()
        text = target.read_text(encoding="utf-8", errors="replace")
        out_dir = pathlib.Path(args.out) if args.out else target.with_suffix(target.suffix + ".tasks")
        prepare(text, out_dir, args.target_lines, args.genre)
        return 0

    if args.cmd == "assemble":
        vdir = pathlib.Path(args.verdicts).resolve()
        out = pathlib.Path(args.out) if args.out else (vdir.parent / f"credit-ledger-{vdir.parent.name}.md")
        assemble(vdir, out)
        return 0

    return 0


if __name__ == "__main__":
    sys.exit(main())

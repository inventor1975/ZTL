def main():
    print("=" * 68)
    print("AIRLINE-PILOT-001 — ПРИМИРЕНИЕ ПО ВСЕМУ КОРПУСУ")
    print("=" * 68)
    rows = pred = 0
    print("\nСЕМЕЙСТВА ПРАВИЛ:")
    for name, d in FAMILIES.items():
        rows += d["строк"]; pred += d["предикаты"]
        print(f"\n  {name} — строк {d['строк']}, SETTLES {d['settles']}")
        print(f"    {d['статус']}")
    print(f"\n  ВСЕГО строк {rows}, различных предикатных позиций {pred}")

"""Что ЯДРО ПРОЧИТАЛО из таблицы — словами, без модели.

ПРОМЕРЕНО, ПОТОМУ И ЗДЕСЬ. Слепой заполняющий с этим зеркалом дал 20 из 21
против 15 из 21 без него — и обошёл того, кто ВИДЕЛ эталоны (18 из 21). При
этом правил он после зеркала ОДИН документ из 24: остальное сделал сразу,
поняв на первых текстах, что ядро читает. Правило словами говорило то же
самое и не сдвинуло ничего (грунт из 17 разобранных примеров: 15 из 21).

ЗАЧЕМ. Замер 24 парадоксов показал: заполняющий понимает задачу верно и
записывает верно, но КЛАДЁТ ОТНОШЕНИЕ НЕ В ТО ПОЛЕ, и от этого зависит, какой
прибор его увидит. Промерено на одной и той же связи «ровно один из двух»:

    claim: a ^ b                      -> включается СУДЬЯ, паспорт ПУСТ
    ground: ~Tr(b) и ~Tr(a)           -> включается ПАСПОРТ, UNDERDETERMINED

Логически это одно и то же. Приборы — разные. Промпт про этот выбор молчит:
он объясняет, когда claim нужен для ЧИСЕЛ, и ничего не говорит про
пропозициональные отношения, которые не самоссылка.

Правилами словами это уже пробовали лечить — дало мало. Поэтому здесь не
правило, а ЗЕРКАЛО: заполнившему показывают, что из его таблицы вошло в разбор,
а что осталось за бортом. Увидеть, что твоя связь никуда не попала, сильнее,
чем прочитать, что так бывает.

ЧЕГО ЭТО НЕ ДЕЛАЕТ. Не говорит, что верно. Говорит, что ПРОЧИТАНО. Таблица
может быть прочитана целиком и при этом отвечать не на тот вопрос.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import zfl2  # noqa: E402

СТАТУС = {
    "verified": "проверено",
    "refuted": "опровергнуто",
    "unverified": "НЕ проверено",
    "defined": "определено формулой",
}
ПРИБОРЫ = {
    "passport": "паспорт (самоссылка, петли, разрешимость)",
    "numeric": "числовой этаж",
    "ledger": "реестр оснований",
    "epoch": "временной слой",
    "judge": "судья утверждения (claim)",
}


def связь_мимо_приборов(doc: dict) -> list:
    """Строки, чья зависимость записана так, что ни один прибор её не прочтёт.

    ПРИЗНАК ТОЧНЫЙ, И ОН НЕ ПЕРВЫЙ, КОТОРЫЙ Я ПРОБОВАЛ. Сперва здесь считались
    строки, не упомянутые в отчёте ядра, — и это оказалось неверно в корне:
    паспорт называет только ПРОБЛЕМНЫЕ компоненты, а обычные проверенные факты
    не упоминает по праву. На 24 эталонных документах та проверка кричала на
    двух ВЕРНЫХ (Рассел, где восемь строк вселенной прибору не нужны, и «тот же
    человек», где obs — просто факт из рассказа), а на «безобидном мире Смита»
    заставила форка дописать лишний claim и испортить годный документ.
    Проверено измерением, а не рассуждением, и первая редакция снята.

    ЧТО ОСТАЛОСЬ. Ровно один случай, промеренный на догме Агриппы: строка
    объявлена проверенной, а её основание — ИМЯ ДРУГОЙ СТРОКИ этой же таблицы
    (`ground_kind: row`). Читается это как происхождение, не как логическая
    связь: паспорт по такому основанию не пойдёт, и «утверждение стоит на
    самодержащемся фундаменте» выходит просто «проверено». Валидатор молчит,
    потому что ошибки и нет.

    ЧЕГО ЭТО НЕ ЛОВИТ — сказано вслух: случай, где связь ушла в claim к судье
    вместо паспорта, ловится отдельной проверкой ниже; а «тот же ли человек»
    не ловится ничем из этого, там спор о самой формализации.
    """
    имена = {(r.get("name") or "").strip() for r in (doc.get("rows") or [])}
    беда = []
    for row in (doc.get("rows") or []):
        основание = (row.get("ground") or "").strip()
        if row.get("ground_kind") == "row" and основание in имена:
            беда.append(((row.get("name") or "").strip(), основание))
    return беда


def факты(doc: dict) -> dict:
    """То же зеркало, но СТРУКТУРОЙ, а не словами.

    ПОЧЕМУ ДВЕ ФОРМЫ. Текст нужен модели: она читает его как читал бы человек,
    и на этом промерены 20 из 21. Экран же говорит на семи языках, и имена
    приборов там ЛОКАЛИЗОВАНЫ ДАВНО. Отдавать в интерфейс русский абзац
    значило бы завести восьмое, кривое описание — прямо тот случай, когда
    подпись и правило разъезжаются.

    Поэтому наружу идут ФАКТЫ, а слова к ним подбирает тот, кто знает язык
    читателя. Ключи приборов те же, что в `applies`, — переводить их незачем,
    перевод уже есть.
    """
    doc = zfl2.coerce(doc)
    r = zfl2.run(doc)
    применились = [k for k, v in (r.get("applies") or {}).items() if v]
    claim = (doc.get("claim") or "").strip()
    паспорт_молчит = not (r.get("applies") or {}).get("passport")
    return {
        "rows": [{"name": row.get("name", ""), "status": row.get("status", ""),
                  "means": row.get("means", ""), "ground": row.get("ground", ""),
                  "value": row.get("value", "")}
                 for row in (doc.get("rows") or [])],
        "claim": claim,
        "applied": применились,
        "silent": [k for k, v in (r.get("applies") or {}).items() if not v],
        "nothing_applied": not применились,
        # Единственное предупреждение, и оно узкое: связь ушла в claim, а
        # паспорт промолчал. Широкое предупреждение перестают читать.
        "claim_bypassed_passport": bool(claim) and паспорт_молчит,
        "связь_мимо_приборов": [{"row": и, "ground_row": к}
                                for и, к in связь_мимо_приборов(doc)],
        "errors": [{"code": i.get("code"), "where": i.get("where"),
                    "hint": i.get("hint")}
                   for i in (r.get("issues") or []) if i.get("level") == "error"],
    }


def прочитано(doc: dict) -> str:
    doc = zfl2.coerce(doc)
    r = zfl2.run(doc)
    строки = []

    строки.append("ЧТО ЯДРО ПРОЧИТАЛО ИЗ ВАШЕЙ ТАБЛИЦЫ")
    строки.append("")
    for i, row in enumerate(doc.get("rows") or [], 1):
        имя = row.get("name", "?")
        ст = СТАТУС.get(row.get("status"), row.get("status") or "?")
        куски = [f"  {i}. «{имя}» — {ст}"]
        if row.get("means"):
            куски.append(f"     истинно, когда: {row['means']}")
        if row.get("ground"):
            куски.append(f"     основание: {row['ground']}")
        if row.get("value") not in (None, ""):
            куски.append(f"     величина: {row['value']}")
        строки.extend(куски)
    claim = (doc.get("claim") or "").strip()
    строки.append("")
    строки.append(f"  утверждение (claim): {claim if claim else '— пусто —'}")

    применились = [k for k, v in (r.get("applies") or {}).items() if v]
    молчат = [k for k, v in (r.get("applies") or {}).items() if not v]
    строки.append("")
    строки.append("КАКИЕ ПРИБОРЫ ЭТО ЗАДЕЛО")
    if применились:
        for k in применились:
            строки.append(f"  ДА  {ПРИБОРЫ.get(k, k)}")
    else:
        строки.append("  НИ ОДИН. Таблица разобрана, и ни один прибор не нашёл,")
        строки.append("  о чём говорить: ответа не будет вообще.")
    for k in молчат:
        строки.append(f"  нет {ПРИБОРЫ.get(k, k)}")

    # ГЛАВНОЕ МЕСТО. Связь, положенная в claim, к паспорту НЕ ПОПАДАЕТ.
    if claim and not (r.get("applies") or {}).get("passport"):
        строки.append("")
        строки.append("  ВНИМАНИЕ. Отношение записано в claim, и его читает СУДЬЯ.")
        строки.append("  Паспортный прибор смотрит только основания строк, то есть")
        строки.append("  поле ground у строк со статусом «определено формулой».")
        строки.append("  Если вы хотели, чтобы связь между строками разбирал ПАСПОРТ")
        строки.append("  (петли, самоссылка, разрешимость) — её место в ground, а не")
        строки.append("  в claim. Одна и та же связь в разных полях уходит к разным")
        строки.append("  приборам, и это не опечатка, а выбор.")

    мимо = связь_мимо_приборов(doc)
    for имя_строки, на_кого in мимо:
        строки.append("")
        строки.append(f"  ВНИМАНИЕ. У строки «{имя_строки}» основанием стоит другая")
        строки.append(f"  строка — «{на_кого}», — и это ПРОИСХОЖДЕНИЕ, а не логическая")
        строки.append("  связь. Паспорт по такому основанию не пойдёт: он читает")
        строки.append("  формулы в ground у строк со статусом «определено формулой».")
        строки.append(f"  Если «{имя_строки}» должна ЗАВИСЕТЬ от «{на_кого}» — статус")
        строки.append(f"  «определено формулой», основание «Tr({на_кого})».")

    отчёт = r.get("report") or {}
    паспорт = отчёт.get("passport") or []
    if паспорт:
        строки.append("")
        строки.append("ПАСПОРТ")
        for p in паспорт:
            строки.append(f"  {', '.join(p.get('component') or [])}: {p.get('kind')}"
                          + (f" — {p.get('detail')}" if p.get("detail") else ""))
    беды = [i for i in (r.get("issues") or []) if i.get("level") == "error"]
    if беды:
        строки.append("")
        строки.append("ОШИБКИ")
        for i in беды:
            строки.append(f"  {i.get('code')} в {i.get('where')}: {i.get('hint')}")
    return "\n".join(строки)


def main() -> int:
    if len(sys.argv) < 2:
        print("backread.py <документ.json | -> ")
        return 2
    сырое = (sys.stdin.read() if sys.argv[1] == "-"
             else Path(sys.argv[1]).read_text(encoding="utf-8"))
    doc = json.loads(сырое)
    if "rows" not in doc:            # файл-набор: показать по ключу
        ключ = sys.argv[2] if len(sys.argv) > 2 else None
        d = doc.get("docs", doc)
        if ключ is None:
            print("в файле набор; второй довод — имя случая:")
            for k in list(d)[:30]:
                print("   ", k)
            return 2
        doc = d[ключ]
    print(прочитано(doc))
    return 0


if __name__ == "__main__":
    sys.exit(main())
